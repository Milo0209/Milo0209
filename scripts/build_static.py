#!/usr/bin/env python3
"""Render all static design assets to assets/ (run manually; contains no data)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import cards  # noqa: E402
from common import atomic_write  # noqa: E402

A = Path(__file__).resolve().parent.parent / "assets"
out = {
    "header.svg": cards.render_header_card(),
    "linkedin.svg": cards.render_linkedin(),
    "sec-featured.svg": cards.render_section("Featured projects", "source stays private \u2013 each project has a public write-up"),
    "sec-workflow.svg": cards.render_section("How I work", "from spec to a system that reports back"),
    "sec-security.svg": cards.render_section("Security mindset", "the stats below come from a pipeline built under these rules"),
    "sec-stats.svg": cards.render_section("Live stats", "generated by scripts in this repo \u2013 sums only, no names, no paths"),
    "workflow.svg": cards.render_workflow(),
    "security.svg": cards.render_security(),
    "footer.svg": cards.render_footer(),
}
for name, desc, tags, status, icon in cards.PROJECTS:
    out[f"project-{name}.svg"] = cards.render_project_card(name, desc, tags, status, icon)
for fn, svg in out.items():
    atomic_write(A / fn, svg)
print(f"built {len(out)} static assets")
